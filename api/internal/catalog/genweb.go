const genHeader = "// generated by cmd/templates gen-web; do not edit\n"

// GenerateWeb writes the typed catalog the web app imports to <webDir>/lib/kit/generated and returns the
// number of files written. Output is deterministic (sorted keys, no timestamps), so CI can diff it.
func GenerateWeb(c *Catalog, webDir string) (int, error) {
	dir := filepath.Join(webDir, "lib", "kit", "generated")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return 0, err
	}
	files := map[string]string{
		"manifests.ts":       genManifests(c),
		"registry.ts":        genRegistry(c),
		"registry.client.ts": genRegistryClient(c),
		"palettes.ts":        genPalettes(c),
		"fonts.ts":           genFonts(c),
		"music.ts":           genMusic(c),
		"sections.ts":        genSections(c),
	}
	for name, body := range files {
		if err := writeIfChanged(filepath.Join(dir, name), genHeader+body); err != nil {
			return 0, err
		}
	}
	return len(files), nil
}

func writeIfChanged(path, body string) error {
	if old, err := os.ReadFile(path); err == nil && string(old) == body {
		return nil
	}
	return os.WriteFile(path, []byte(body), 0o644)
}

// live lists the slugs that have a coded renderer and are published (the guest route switches on these).
func live(c *Catalog) []Template {
	var out []Template
	for _, t := range c.Templates {
		if t.Manifest.Kind == "coded" && t.Manifest.Status == "published" {
			out = append(out, t)
		}
	}
	return out
}

func tsJSON(v any) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	_ = enc.Encode(v)
	return strings.TrimRight(buf.String(), "\n")
}

func genManifests(c *Catalog) string {
	m := map[string]any{}
	for _, t := range c.Templates {
		m[t.Manifest.Slug] = t.Raw
	}
	return `
export type ColorRole = "bg" | "surface" | "ink" | "inkSoft" | "muted" | "accent" | "accentSoft" | "line" | "danger" | "onAccent";
export type SectionType = "hero" | "opening" | "story" | "schedule" | "gallery" | "gift" | "rsvp" | "wishes" | "music" | "closing";
export type MotionLevel = "full" | "calm" | "off";

export type Manifest = {
  manifestVersion: 1;
  slug: string;
  name: string;
  kind: "coded" | "themed";
  renderer?: string;
  status: "draft" | "published" | "retired";
  access: "free" | "premium";
  category: string;
  eventTypes: string[];
  tags: string[];
  position: number;
  palette: string;
  marketing: { desc: string; style: string; mood: string; demo?: { route: string } };
  sections: { type: SectionType; required?: boolean; hiddenUntilFilled?: boolean; max?: number }[];
  capabilities: {
    music: boolean; gallery: { max: number }; wishes: boolean; rsvp: boolean; gift: boolean; timezone: boolean;
    multiMoment: { max: number }; languages: ("en" | "id" | "ms")[]; needsWebGL: boolean; reducedMotion: "static" | "calm";
  };
  tokens: {
    color: Record<ColorRole, string>;
    font: { display: string; body: string; script: string; mono?: string };
    motion: { level: MotionLevel; durationScale?: number };
    extra?: Record<string, string>;
  };
  customizable: { palette: string[]; fontPairings: string[]; tokens: string[]; motion: MotionLevel[] };
  layout?: { block: string; variant?: string; visibleWhen?: "always" | "filled" }[];
  thumbnail: string;
  thumbnailMobile?: string;
  budget?: { jsGzKb: number };
};

export const MANIFESTS: Record<string, Manifest> = ` + tsJSON(m) + ` as Record<string, Manifest>;
`
}

func genRegistry(c *Catalog) string {
	var slugs []string
	for _, t := range live(c) {
		slugs = append(slugs, fmt.Sprintf("%q", t.Manifest.Slug))
	}
	return `// Server-safe: no component imports. Which slugs have a coded renderer (the guest route and the demo
// route switch on this); the components load through registry.client.ts.
export const TEMPLATE_SLUGS = [` + strings.Join(slugs, ", ") + `] as const;
export type TemplateSlug = (typeof TEMPLATE_SLUGS)[number];

export const hasLiveTemplate = (slug: string | null | undefined): slug is TemplateSlug => !!slug && (TEMPLATE_SLUGS as readonly string[]).includes(slug);
`
}

func genRegistryClient(c *Catalog) string {
	var b strings.Builder
	b.WriteString(`// Client-only: one lazily loaded chunk per coded template. Dynamic imports must be literal for the bundler,
// hence generated.
import { createElement, type ComponentType } from "react";
import dynamic from "next/dynamic";
import type { TemplateProps } from "@/components/templates/types";
import { Waiting } from "@/components/templates/Waiting";
import type { TemplateSlug } from "./registry";

export const RENDERERS: Record<TemplateSlug, ComponentType<TemplateProps>> = {
`)
	for _, t := range live(c) {
		fmt.Fprintf(&b, "  %q: dynamic(() => import(\"@/components/templates/%s\"), { ssr: false, loading: () => createElement(Waiting, { slug: %q }) }),\n", t.Manifest.Slug, t.Manifest.Renderer, t.Manifest.Slug)
	}
	b.WriteString("};\n")
	return b.String()
}

func genPalettes(c *Catalog) string {
	return `export type Palette = { id: string; name: string; swatch: string[]; color: Record<string, string>; extra?: Record<string, string>; aliases: string[] };

export const PALETTES: Palette[] = ` + tsJSON(c.Palettes) + `;
`
}

func genFonts(c *Catalog) string {
	fam := map[string]FontFamily{}
	for k, v := range c.Fonts.Families {
		fam[k] = v
	}
	return `export type FontFile = { src: string; style: "normal" | "italic"; weight: string };
export type FontFamily = { name: string; license: string; fallback: string; files: FontFile[] };
export type FontPairing = { id: string; name: string; display: string; body: string; script: string; mono?: string };

export const FONT_FAMILIES: Record<string, FontFamily> = ` + tsJSON(fam) + `;

export const FONT_PAIRINGS: FontPairing[] = ` + tsJSON(c.Fonts.Pairings) + `;
`
}

func genMusic(c *Catalog) string {
	return `export type Track = { key: string; title: string; credit: string; src: string; license: string; durationMs: number };

export const TRACKS: Track[] = ` + tsJSON(c.Tracks) + `;
`
}

// genSections emits the section content schema ($defs) for the generic admin form.
func genSections(c *Catalog) string {
	defs := map[string]any{}
	if c.Sections != nil {
		keys := make([]string, 0)
		for k := range c.Sections.root["$defs"].(map[string]any) {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			defs[k] = c.Sections.Def(k)
		}
	}
	return `// Content shape of each section type (catalog/sections.schema.json). x-* keys drive the admin form.
export type FieldSchema = {
  type?: "string" | "array" | "object";
  maxLength?: number;
  maxItems?: number;
  pattern?: string;
  required?: string[];
  items?: FieldSchema;
  properties?: Record<string, FieldSchema>;
  "x-label"?: string;
  "x-widget"?: "textarea" | "media" | "media-list" | "chapters" | "gallery" | "track";
  "x-hint"?: string;
  "x-placeholder"?: string;
  "x-max"?: string;
  "x-order"?: number;
};

export const SECTION_SCHEMAS: Record<string, FieldSchema> = ` + tsJSON(defs) + `;
`
}
